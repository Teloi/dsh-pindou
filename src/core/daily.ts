// ── which pattern is today's (spec §18.3, decision 03:26) ─────────────
const DAY = 86_400_000
/**
 * Day 0 of the sequence: 2026-01-01 (a local calendar day) shows DAILY_DEFS[0], the designer's
 * day 01 (胡萝卜); every later day the next one, back to the start after 60 days. Deterministic
 * and the same on every device for the same local date, no network.
 */
export const DAILY_EPOCH = Date.UTC(2026, 0, 1)

/**
 * Whole days from the epoch to the local calendar day of `at` (negative before it). The local
 * year, month and day go through Date.UTC, so a 23- or 25-hour DST day is still one day.
 */
export function dailyDay(at: number): number {
  const d = new Date(at)
  return (Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - DAILY_EPOCH) / DAY
}

/** The pattern of day `day`: the day number mod 60, never negative. */
export const dailyIndex = (day: number): number => ((day % DAILY_DEFS.length) + DAILY_DEFS.length) % DAILY_DEFS.length

/** 「2026-10-30」: the date of day `day`, as it goes into the source key. */
export const dailyDate = (day: number): string => new Date(DAILY_EPOCH + day * DAY).toISOString().slice(0, 10)

/** The day number of a 「2026-10-30」 date (NaN for anything else). */
export const dailyDayOf = (date: string): number => /^\d{4}-\d\d-\d\d$/.test(date) ? (Date.parse(date) - DAILY_EPOCH) / DAY : Number.NaN

/**
 * Whether a daily work counts for the streak (spec §18.3): it is finished (拼完: the ironed board is
 * that day's pattern exactly, every bead in place and none extra, like completion().done) and it was
 * ironed on that very day (a 补拼 of an older daily, or one finished past midnight, does not count).
 */
export function dailyCounts(date: string, w: { readonly i: number; readonly b: string }): boolean {
  const day = dailyDayOf(date)
  return dailyDay(w.i) === day && w.b === DAILY_DEFS[dailyIndex(day)]?.rows.join('')
}

/**
 * Streak (spec §18.3, derived, never stored): consecutive days with a daily work, ending today,
 * or yesterday while today's is still to do. Deleting a work can shorten it.
 */
export function dailyStreak(days: Iterable<number>, today: number): number {
  const done = new Set(days)
  let d = done.has(today) ? today : today - 1
  let n = 0
  while (done.has(d)) { n++; d-- }
  return n
}
